    { code = "auto", key = "LANG_AUTO" },
    { code = "enUS", label = "English" },
    { code = "frFR", label = "Français" },
}

local active = strings.enUS

ns.L = setmetatable({}, {
    __index = function(_, key)
        return active[key] or strings.enUS[key] or key
    end,
})

function ns.ApplyLanguage(code)
    if code == nil or code == "auto" then code = GetLocale() end
    active = strings[code] or strings.enUS
end

ns.ApplyLanguage("auto")
